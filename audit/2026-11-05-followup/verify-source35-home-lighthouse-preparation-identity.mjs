import assert from 'node:assert/strict';
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { verifyFrozenSource } from '../2026-10-21/artifact-verification.mjs';
const directory = 'audit/2026-11-05-followup';
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const sourceFile = `${directory}/final35-source.json`;
const source = await verifyFrozenSource(sourceFile);
assert.equal(source.receipt.compared, 506);
assert.deepEqual(source.receipt.mismatches, []);
assert.equal(source.frozen.local.version, 'd89f84d74519bf2bbae0');
assert.equal(source.frozen.baseline, '9b21e255ea1840508cbc35b625d0ccde8f3af7cc');
const preparationFile = `${directory}/source35-home-lighthouse-preparation.json`;
const preparationBytes = await readFile(preparationFile);
const preparation = JSON.parse(preparationBytes);
for (const row of preparation.files) assert.equal(hash(await readFile(row.target)), row.targetSha256);
const names = [...(await readdir('e2e')).filter(file => file.endsWith('.ts')).map(file => `e2e/${file}`), 'playwright.config.ts'].sort();
assert.equal(names.length, 73);
const dependencyHashes = Object.fromEntries(await Promise.all(names.map(async file => [file, hash(await readFile(file))])));
const receipt = { status: 'PASS-SCOPED-PREPARATION-IDENTITY-NOT-RUNTIME', recordedAt: new Date().toISOString(), source: source.receipt, sourceManifestSha256: hash(await readFile(sourceFile)), actualBuild: source.frozen.local.version, preparation: { file: preparationFile, sha256: hash(preparationBytes) }, preparedHelperHashesMatch: true, dependencyCount: names.length, dependencySha256: hash(JSON.stringify(dependencyHashes)), dependencyHashes, testOrMeasurementExecution: false, existingFilesEdited: false };
await writeFile(`${directory}/source35-home-lighthouse-current-identity.json`, JSON.stringify(receipt, null, 2), { flag: 'wx' });
console.log(JSON.stringify({ status: receipt.status, sourceFiles: source.receipt.compared, sourceManifestSha256: receipt.sourceManifestSha256, dependencies: names.length, dependencySha256: receipt.dependencySha256 }));
