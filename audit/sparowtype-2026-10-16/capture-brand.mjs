import { chromium } from '@playwright/test';
import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';

const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.clock.install();
await page.goto('http://127.0.0.1:4173/');
await page.getByTestId('opening-experience').waitFor();
await page.clock.pauseAt(new Date(await page.evaluate(() => Date.now()) + 20));
for (const [time, name] of [[650, 'opening-keyboard'], [1750, 'opening-sparrow']]) {
  await page.evaluate(time => document.getAnimations().forEach(animation => {
    animation.pause();
    animation.currentTime = time;
  }), time);
  await page.screenshot({ path: `audit/sparowtype-2026-10-16/${name}.png` });
}
await page.getByRole('button', { name: /^Skip intro/ }).click();
await page.getByRole('textbox', { name: 'Typing input', exact: true }).waitFor();
await page.clock.resume();
await page.evaluate(() => document.fonts.ready);
await page.screenshot({ path: 'audit/sparowtype-2026-10-16/practice-dark.png', fullPage: true });
await page.getByRole('button', { name: 'Switch to light theme', exact: true }).click();
await page.waitForFunction(() => document.documentElement.dataset.theme === 'sparow-light');
await page.getByRole('textbox', { name: 'Typing input', exact: true }).focus();
await page.screenshot({ path: 'audit/sparowtype-2026-10-16/practice-light.png', fullPage: true, animations: 'disabled' });
await page.setViewportSize({ width: 390, height: 844 });
await page.screenshot({ path: 'audit/sparowtype-2026-10-16/practice-light-mobile.png', fullPage: true, animations: 'disabled' });
await page.goto('http://127.0.0.1:4173/settings');
await page.getByRole('heading', { name: 'Your practice, your space.' }).waitFor();
await page.screenshot({ path: 'audit/sparowtype-2026-10-16/settings-mobile.png', fullPage: true });
await page.setViewportSize({ width: 1440, height: 1000 });
await page.goto('http://127.0.0.1:4173/');
await page.getByRole('group', { name: 'Test mode', exact: true }).getByRole('button', { name: 'Custom', exact: true }).click();
await page.getByRole('textbox', { name: 'Custom practice passage', exact: true }).fill('cat');
await page.getByRole('button', { name: 'Start private practice', exact: true }).click();
const input = page.getByRole('textbox', { name: 'Typing input', exact: true });
await input.focus();
await input.pressSequentially('cx', { delay: 70 });
await input.press('Backspace');
await input.pressSequentially('at', { delay: 70 });
const results = page.getByRole('region', { name: 'Session results', exact: true });
await results.waitFor();
await page.screenshot({ path: 'audit/sparowtype-2026-10-16/results-light.png', fullPage: true, animations: 'disabled' });
const downloadEvent = page.waitForEvent('download');
await results.getByRole('button', { name: 'Share image', exact: true }).click();
const download = await downloadEvent;
assert.equal(download.suggestedFilename(), 'sparowtype-result.png');
const sharePath = 'audit/sparowtype-2026-10-16/result-share-light.png';
await download.saveAs(sharePath);
const png = await readFile(sharePath);
assert.equal(png.readUInt32BE(16), 1200);
assert.equal(png.readUInt32BE(20), 630);
const background = await page.evaluate(async bytes => {
  const image = await createImageBitmap(new Blob([new Uint8Array(bytes)], { type: 'image/png' }));
  const canvas = document.createElement('canvas');
  canvas.width = image.width;
  canvas.height = image.height;
  const ctx = canvas.getContext('2d');
  ctx.drawImage(image, 0, 0);
  return [...ctx.getImageData(0, 0, 1, 1).data];
}, [...png]);
assert.deepEqual(background, [246, 247, 250, 255]);
await writeFile('audit/sparowtype-2026-10-16/share-light-check.json', JSON.stringify({ filename: download.suggestedFilename(), width: 1200, height: 630, background }, null, 2));
await writeFile('audit/sparowtype-2026-10-16/capture-errors.json', JSON.stringify(errors, null, 2));
await browser.close();
