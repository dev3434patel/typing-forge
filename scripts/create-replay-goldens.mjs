import { mkdtemp, readFile, writeFile, unlink, rmdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import os from 'node:os';
import { pathToFileURL } from 'node:url';
import ts from 'typescript';

// Intentional baseline updates are separate from tests. Never called by test:run.
if (!process.argv.includes('--write-baseline')) throw new Error('Pass --write-baseline only after reviewing a metric-contract change. Tests never regenerate goldens.');
const root = path.resolve(import.meta.dirname, '..');
const temporary = await mkdtemp(path.join(os.tmpdir(), 'sparowtype-goldens-'));
const names = ['types', 'transcript', 'metrics', 'session'];
try {
  for (const name of names) {
    const source = (await readFile(path.join(root, `src/lib/typing-core/${name}.ts`), 'utf8')).replace(/from ['"]\.\/(types|transcript|metrics|session)\.ts['"]/g, (_, item) => `from './${item}.mjs'`);
    await writeFile(path.join(temporary, `${name}.mjs`), ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ES2022, target: ts.ScriptTarget.ES2022 } }).outputText);
  }
  const { SessionController } = await import(pathToFileURL(path.join(temporary, 'session.mjs')));
  const { replaySession } = await import(pathToFileURL(path.join(temporary, 'metrics.mjs')));
  const { graphemes } = await import(pathToFileURL(path.join(temporary, 'transcript.mjs')));
  const fixtures = [];
  const samples = [
    ['latin', 'calm clear'], ['nfc', 'café naïve'], ['nfd', 'e\u0301 cole'],
    ['hindi', 'कमल भारत'], ['conjunct', 'क्ष ज्ञ त्र'], ['arabic', 'نور سلام'],
    ['emoji', '👩‍💻 👍🏽'], ['flags', '🇮🇳 🇺🇸'], ['cyrillic', 'мир дом'],
    ['greek', 'α β γ'], ['code', 'a = 1;\n\treturn a;'], ['bidi', 'a مرحبا b'],
  ];
  for (const [name, text] of samples) for (const variant of ['exact', 'corrected', 'composition']) {
    let now = 0;
    const session = new SessionController({ clientSessionId: `golden-${name}-${variant}`, mode: 'custom', initialTarget: text, scoringPolicy: 'code', privacy: 'private-custom', keyboardLayout: 'qwerty' }, { now: () => now, wallNow: () => 1792540800000 + now });
    const units = graphemes(text);
    const input = edit => { now += 137; session.input(edit); };
    if (variant === 'corrected') { input({ type: 'insert', text: 'x' }); input({ type: 'delete', start: 0, end: 1 }); }
    units.forEach((unit, index) => input(variant === 'composition' ? { type: 'composition', text: unit, compositionId: `${name}-${index}`, provenance: 'composition' } : { type: 'insert', text: unit }));
    now += 1200;
    const result = session.result || session.finish('manual');
    const options = { targetText: result.targetText, issuedTargetSegments: result.issuedTargetSegments, pauseIntervals: result.pauseIntervals };
    const replay = replaySession(result.configuration, result.events, result.elapsedMs, options);
    fixtures.push({ name: `${name}-${variant}`, schemaVersion: 3, configuration: result.configuration, events: result.events, elapsedMs: result.elapsedMs, options, expected: { finalText: replay.finalText, cursor: replay.cursor, metrics: replay.metrics, sha256: createHash('sha256').update(JSON.stringify(replay)).digest('hex') } });
  }
  for (const policy of ['current-word', 'correct-words-locked']) {
    let now = 0;
    const session = new SessionController({ clientSessionId: `golden-${policy}`, mode: 'time', durationMs: 30000, initialTarget: 'cat dog fox', correctionPolicy: policy }, { now: () => now, wallNow: () => 1792540800000 + now });
    for (const edit of [{ type: 'insert', text: 'cxt ' }, { type: 'delete' }, { type: 'delete' }, { type: 'insert', text: 'at ' }, { type: 'insert', text: 'd' }]) { session.input(edit); now += 200; }
    session.pause(); now += 1000; session.resume(); now += 5000;
    const result = session.finish('manual');
    const options = { targetText: result.targetText, issuedTargetSegments: result.issuedTargetSegments, pauseIntervals: result.pauseIntervals };
    const replay = replaySession(result.configuration, result.events, result.elapsedMs, options);
    fixtures.push({ name: `correction-${policy}-pause`, schemaVersion: 3, configuration: result.configuration, events: result.events, elapsedMs: result.elapsedMs, options, expected: { finalText: replay.finalText, cursor: replay.cursor, metrics: replay.metrics, sha256: createHash('sha256').update(JSON.stringify(replay)).digest('hex') } });
  }
  const output = path.join(root, 'src/lib/typing-core/__tests__/fixtures/replay-v3.json');
  await writeFile(output, JSON.stringify({ baseline: 'forge-v3 / 21 October 2026; expected values frozen, never regenerated by tests', schemaVersion: 3, fixtures }, null, 2) + '\n');
  process.stdout.write(`Wrote ${fixtures.length} immutable replay fixtures. Review changes before committing.\n`);
} finally {
  for (const name of names) await unlink(path.join(temporary, `${name}.mjs`)).catch(error => { if (error.code !== 'ENOENT') throw error; });
  await rmdir(temporary);
}
